const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const code=fs.readFileSync('script.js','utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
for(const m of code.matchAll(/\$\('([^']+)'\)/g))assert.ok(ids.includes(m[1]),'Missing element '+m[1]);
const nodes=Object.fromEntries(ids.map(id=>[id,{value:'',textContent:'',innerHTML:'',hidden:false,disabled:false,addEventListener(){},setAttribute(){},classList:{toggle(){}},showModal(){this.open=true;},close(){this.open=false;},reset(){this.wasReset=true;}}]));
let response,posted,lastUrl,startup,timerId=0;
const timers=new Map();
const ctx={console,Date,Intl,URLSearchParams,AbortController,encodeURIComponent,setTimeout:callback=>{timers.set(++timerId,callback);return timerId;},clearTimeout:id=>timers.delete(id),window:{addEventListener(){}},location:{hash:''},history:{replaceState(){}},sessionStorage:{getItem:()=>'',setItem(){},removeItem(){}},document:{getElementById:id=>nodes[id],querySelectorAll:()=>[],addEventListener:(event,callback)=>{startup=callback;}},fetch:async(url,options)=>{lastUrl=url;posted=options;return response;}};
const savedAccess={};
ctx.localStorage={getItem:key=>savedAccess[key]||null,setItem:(key,value)=>{savedAccess[key]=value;},removeItem:key=>{delete savedAccess[key];}};
vm.createContext(ctx);vm.runInContext(code,ctx);
const json=value=>({ok:true,text:async()=>JSON.stringify(value)});
(async()=>{
  response=json({success:true,leads:[]});
  startup();
  await new Promise(setImmediate);
  assert.equal(nodes.connection.textContent,'Google Sheets connected');
  assert.equal(nodes.modeBanner.hidden,true);
  await vm.runInContext("api('getLeads')",ctx);
  assert.ok(lastUrl.includes('AKfycbxKL-uC53lSZCHTMwSUYcgNJIlT7CsxgTaMRSy9wIBmgUsoEWxjBMEb5lN9sySXlbVr/exec'));
  assert.equal(posted.method,'POST');assert.equal(posted.credentials,'omit');
  assert.deepEqual(JSON.parse(posted.body.get('payload')),{action:'getLeads'});
  response={ok:true,text:async()=>'<html>Script function not found: doPost</html>'};
  await assert.rejects(vm.runInContext("api('getLeads')",ctx),/instead of JSON/);
  response=json({success:false,code:'AUTH_REQUIRED',message:'Access denied'});
  await assert.rejects(vm.runInContext("api('getLeads')",ctx),e=>e.code==='AUTH_REQUIRED');
  const lead={id:'saved-id',name:'Test Customer',contact:'9876543210',interestedIn:['Gym Setup'],source:'Walk-in',notes:'',followUpDate:'2099-01-01',createdAt:new Date().toISOString(),status:'New',version:1,history:[]};
  for(const id of ['name','contact','source','notes','followUpDate'])nodes[id].value=lead[id];
  nodes.interestedIn.value='Gym Setup';
  response=json({success:true,lead});
  vm.runInContext('state.ready=true;',ctx);
  await vm.runInContext('saveEnquiry({preventDefault(){}})',ctx);
  assert.equal(JSON.parse(posted.body.get('payload')).action,'createLead');
  assert.deepEqual(JSON.parse(posted.body.get('payload')).interestedIn,['Gym Setup']);
  assert.equal(nodes.enquiryForm.wasReset,true);
  assert.equal(nodes.whatsappDialog.open,true);
  assert.ok(nodes.whatsappLink.href.startsWith('https://wa.me/919876543210?text='));
  assert.ok(decodeURIComponent(nodes.whatsappLink.href).includes('Test Customer'));
  assert.ok(!html.includes('id="whatsappPreview"'));
  assert.ok(html.includes('Send WhatsApp message?'));
  assert.equal(nodes.toast.textContent,'Enquiry saved to Google Sheets.');
  // An unsuccessful network save must keep the form and retry identifier.
  nodes.enquiryForm.wasReset=false;nodes.whatsappDialog.open=false;
  response=json({success:false,message:'Sheet not configured'});
  await vm.runInContext('saveEnquiry({preventDefault(){}})',ctx);
  const firstRequest=JSON.parse(posted.body.get('payload')).requestId;
  assert.equal(nodes.enquiryForm.wasReset,false);assert.equal(nodes.whatsappDialog.open,false);
  await vm.runInContext('saveEnquiry({preventDefault(){}})',ctx);
  assert.equal(JSON.parse(posted.body.get('payload')).requestId,firstRequest);
  assert.ok(!code.includes('readDemo'));
  response=json({success:true,leads:[]});
  await vm.runInContext('loadLeads()',ctx);
  assert.equal(nodes.connection.textContent,'Google Sheets connected');
  assert.ok(!html.includes('accessDialog')&&!html.includes('staffAccessBtn'));
  assert.ok(!code.includes('staffAccessCode'));
  assert.equal(nodes.saveEnquiry.disabled,false);
  response=json({success:false,code:'AUTH_REQUIRED',message:'Old backend'});
  await vm.runInContext('loadLeads()',ctx);
  assert.ok(nodes.connectionHelp.textContent.includes('deploy a new version'));
  assert.equal(nodes.saveEnquiry.disabled,true);
  assert.equal(nodes.retryConnection.hidden,false);
  const originalFetch=ctx.fetch;
  ctx.fetch=(url,options)=>new Promise((resolve,reject)=>options.signal.addEventListener('abort',()=>{const error=new Error('Aborted');error.name='AbortError';reject(error);}));
  const stalledRequest=vm.runInContext("api('getLeads')",ctx);
  const rejected=assert.rejects(stalledRequest,/did not respond in time/);
  timers.get(timerId)();
  await rejected;
  ctx.fetch=originalFetch;
  response=json({success:true,leads:[]});
  await vm.runInContext('loadLeads()',ctx);
  assert.equal(nodes.modeBanner.hidden,true);
  assert.equal(nodes.saveEnquiry.disabled,false);
  assert.ok(/src="script\.js\?v=[a-f0-9]+"/.test(html));
  console.log('Startup, HTTP saves, retries, timeout recovery and versioned assets checks passed.');
})().catch(error=>{console.error(error);process.exitCode=1;});
